#!/usr/bin/env python3
"""Renders the full-colour layer's fonts (engine/hd_fonts.cpp) from their TTFs.

    python3 tools/hd_fonts.py FONT_DIR

FONT_DIR holds JBMono-Medium.ttf and JBMono-Bold.ttf (JetBrains Mono's Medium and Bold,
https://github.com/JetBrains/JetBrainsMono) and VT323.ttf (https://github.com/google/fonts,
ofl/vt323), all SIL OFL 1.1 (LICENSES/).

Each font and size becomes a table of glyphs: 4-bit coverage, rows packed two pixels a byte, placed
from the pen on the baseline. The board and the desktop runtime compile the same tables, so a
preview's text is the board's, pixel for pixel. Run again after changing FONTS or SET.
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

FONTS = [  # name, file, sizes (px), ASCII only (big sizes of the pixel font: flash)
    ("mono", "JBMono-Medium.ttf", [12, 14, 16, 20, 24], False),
    ("bold", "JBMono-Bold.ttf", [16, 18, 24, 32], False),
    ("vt", "VT323.ttf", [30, 46, 72], True),
]
SET = (list(range(0x20, 0x7F)) + list(range(0xA0, 0x100)) + list(range(0x2010, 0x2028)) + list(range(0x2190, 0x2194)) +
       [0x2500, 0x2502, 0x250C, 0x2510, 0x2514, 0x2518, 0x251C, 0x2524, 0x252C, 0x2534, 0x253C,
        0x2580, 0x2584, 0x2588, 0x258C, 0x2590, 0x2591, 0x2592, 0x2593,
        0x25A0, 0x25B2, 0x25B6, 0x25BC, 0x25C0, 0x25CB, 0x25CF, 0x2605, 0x2665, 0x2713])


def render(font: ImageFont.FreeTypeFont, cp: int):
    """The glyph's coverage (0-15), its box from the pen (x right, y down from the baseline) and advance."""
    ch = chr(cp)
    size = font.size
    img = Image.new("L", (size * 4, size * 4), 0)
    ox, oy = size, size * 3  # the pen, on the baseline
    ImageDraw.Draw(img).text((ox, oy), ch, font=font, fill=255, anchor="ls")
    adv = round(font.getlength(ch))
    box = img.getbbox()
    if not box:
        return None, 0, 0, 0, 0, adv
    x0, y0, x1, y1 = box
    w, h = x1 - x0, y1 - y0
    cov = [(img.getpixel((x, y)) * 15 + 127) // 255 for y in range(y0, y1) for x in range(x0, x1)]
    return cov, w, h, x0 - ox, y0 - oy, adv


def main() -> None:
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    src = Path(sys.argv[1])
    out_dir = Path(__file__).resolve().parent.parent / "engine"
    cpp = ["// Generated by tools/hd_fonts.py from the TTFs (JetBrains Mono, VT323: SIL OFL 1.1).",
           "// Do not edit: run the script again.", '#include "hd_fonts.hpp"', "", "namespace carts::hd_fonts {", ""]
    table, total = [], 0
    for name, file, sizes, ascii_only in FONTS:
        for size in sizes:
            font = ImageFont.truetype(str(src / file), size)
            asc, desc = font.getmetrics()
            notdef = render(font, 0x10FFFD)[0]
            glyphs, bitmap = [], bytearray()
            for cp in SET:
                if ascii_only and cp > 0x7E:
                    continue
                cov, w, h, x, y, adv = render(font, cp)
                if cp != 0x20 and (cov is None or cov == notdef):
                    continue  # not in the font
                off = len(bitmap)
                if cov:
                    for r in range(h):
                        row = cov[r * w:(r + 1) * w] + ([0] if w % 2 else [])
                        bitmap.extend((row[i] << 4) | row[i + 1] for i in range(0, len(row), 2))
                glyphs.append((cp, off, w, h, x, y, adv))
            ident = f"{name}_{size}"
            cpp.append(f"static const uint8_t {ident}_bits[] = {{")
            for i in range(0, len(bitmap), 24):
                cpp.append("  " + ",".join(str(b) for b in bitmap[i:i + 24]) + ",")
            cpp.append("};")
            cpp.append(f"static const Glyph {ident}_glyphs[] = {{")
            for g in glyphs:
                cpp.append("  {%d, %d, %d, %d, %d, %d, %d}," % g)
            cpp.append("};")
            cpp.append("")
            table.append(f'  {{"{name}", {size}, {asc}, {desc}, {len(glyphs)}, {ident}_glyphs, {ident}_bits}},')
            total += len(bitmap) + len(glyphs) * 12
            print(f"{ident}: {len(glyphs)} glyphs, {len(bitmap)} bytes of bitmap")
    cpp.append("const Font kFonts[] = {")
    cpp.extend(table)
    cpp.append("};")
    cpp.append("const int kFontCount = sizeof kFonts / sizeof kFonts[0];")
    cpp.append("")
    cpp.append("}  // namespace carts::hd_fonts")
    (out_dir / "hd_fonts.cpp").write_text("\n".join(cpp) + "\n")
    print(f"total ~{total // 1024} KB of flash")


if __name__ == "__main__":
    main()
